import assert from 'node:assert/strict'
export async function testShell(browser, url) {
  const page = await browser.newPage({ viewport: { width: 1366, height: 900 }, hasTouch: true })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await page.goto(url)
    await page.waitForFunction(() => window.ipadLayoutFixture?.snapshot()?.panels.length === 2)
    const shell = page.locator('.ipad-shell')
    const toggle = side => page.evaluate(side => window.ipadLayoutFixture.ui.getState()[side === 'left' ? 'toggleLeftRail' : 'toggleRightRail'](), side)
    assert.equal((await page.locator('.global-navigation').boundingBox()).width, 56, 'Icon rail remains visible when main sidebar is closed')
    assert.equal((await page.locator('.app-workspace').boundingBox()).x, 56)
    await page.locator('.global-navigation').getByRole('button', { name: '과목', exact: true }).tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'docked')
    await page.locator('.global-navigation').getByRole('button', { name: '과목', exact: true }).tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'closed')
    const tools = page.locator('.global-navigation').getByRole('button', { name: '도구', exact: true })
    await tools.tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'docked')
    await page.getByRole('button', { name: '내 공간 닫기', exact: true }).last().tap()
    await tools.tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'docked')
    assert.equal(await page.evaluate(() => window.ipadLayoutFixture.ui.getState().courseRailOpen), true, 'Tools reopens on the first tap after closing its sidebar')
    await page.getByRole('button', { name: '내 공간 닫기', exact: true }).last().tap()
    await page.evaluate(() => window.ipadLayoutFixture.ui.setState({ leftRailPanel: 'courses' }))
    await page.getByRole('button', { name: '내 공간 열기', exact: true }).tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'docked')
    assert.equal(await page.locator('.global-navigation > .rail-nav__item').count() >= 6, true)
    const navigationBox = await page.locator('.global-navigation').boundingBox()
    const courseBox = await page.locator('.ipad-left-surface').boundingBox()
    assert.equal(navigationBox.x, 0)
    assert.equal(navigationBox.width, 56)
    assert.equal(courseBox.x, 56)
    assert.equal(courseBox.width, 280)
    const courseListBox = await page.locator('.shell-course-rail').boundingBox()
    assert.ok(Math.abs(courseListBox.x - courseBox.x) <= 1 && Math.abs(courseListBox.width - courseBox.width) <= 2, 'Main course list fills its own column without inherited grid-area offsets')
    for (const button of await page.locator('.global-navigation button,.course-row__toggle,.course-group-row__menu-button').all()) {
      const box = await button.boundingBox()
      assert.ok(box && box.width >= 44 && box.height >= 44, 'Production navigation/course touch target')
      assert.notEqual(await button.evaluate(node => getComputedStyle(node).opacity), '0')
    }
    await toggle('right')
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadPinned === 'both')
    assert.ok((await page.locator('.app-workspace').boundingBox()).width >= 560)
    const materialsBox = await page.locator('.ipad-right-surface').boundingBox()
    const listBox = await page.locator('.ipad-right-surface > .app-rail').boundingBox()
    assert.ok(Math.abs(listBox.x - materialsBox.x) <= 1 && Math.abs(listBox.width - materialsBox.width) <= 2, 'Actual materials rail fills its 320px wrapper without inherited grid offsets: ' + JSON.stringify({ materialsBox, listBox, css: await page.locator('.ipad-right-surface > .app-rail').evaluate(e => Object.fromEntries(['width','left','right','position','transform','flex','margin','grid-area'].map(key => [key, getComputedStyle(e).getPropertyValue(key)]))) }))
    const textSelectors = ['.workspace-tab__title', '.ipad-rail-controls strong', '.ipad-rail-controls button', '.rail-search input', '.materials-heading__course', '.favorites-section__heading > span']
    const baseFontSizes = await Promise.all(textSelectors.map(selector => page.locator(selector).first().evaluate(node => parseFloat(getComputedStyle(node).fontSize))))
    for (const theme of ['dark', 'light']) {
      await page.evaluate(theme => { document.documentElement.dataset.theme = theme; document.documentElement.style.setProperty('--font-scale', '1.2') }, theme)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      for (const [index, selector] of textSelectors.entries()) {
        const size = await page.locator(selector).first().evaluate(node => parseFloat(getComputedStyle(node).fontSize))
        assert.ok(Math.abs(size - baseFontSizes[index] * 1.2) < .1, `${selector} scales with the existing UI font setting: ${baseFontSizes[index]} -> ${size}`)
      }
      const context = await page.locator('.materials-heading__course').boundingBox()
      const actions = await page.locator('.materials-heading__actions').boundingBox()
      assert.ok(context.x >= materialsBox.x && context.x + context.width <= materialsBox.x + materialsBox.width && context.y + context.height <= actions.y + 1, 'Long course context wraps above its actions without clipping or overlap')
    }
    await page.evaluate(() => document.documentElement.style.setProperty('--font-scale', '1'))
    await page.locator('textarea[aria-label="second"]').fill('dual panel draft')
    await page.screenshot({ style: '.fixture-materials,.fixture-settings { visibility: hidden; }', path: '/tmp/bandal-ipad-shell-wide-v2.png' })
    await page.setViewportSize({ width: 1194, height: 834 })
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'suspended')
    assert.equal(await shell.getAttribute('data-ipad-materials'), 'docked')
    await page.getByRole('button', { name: '내 공간 열기', exact: true }).tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadMaterials === 'suspended')
    assert.equal(await page.evaluate(() => window.ipadLayoutFixture.ui.getState().leftRailOpen), true, 'Suspended request is promoted')
    await page.setViewportSize({ width: 1366, height: 900 })
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadPinned === 'both')
    assert.equal(await page.locator('textarea[aria-label="second"]').inputValue(), 'dual panel draft')
    await page.getByRole('button', { name: '자료 닫기', exact: true }).tap()
    await page.evaluate(() => window.ipadLayoutFixture.select('first'))
    await page.getByRole('button', { name: '도움 열기 first', exact: true }).tap()
    await page.locator('.tab-assistant:visible .chat-composer__input').fill('문서별 대화 초안 보존')
    const composer = await page.locator('.tab-assistant:visible .chat-composer__input').elementHandle()
    const original = await page.evaluate(() => window.ipadLayoutFixture.snapshot())
    await page.screenshot({ style: '.fixture-materials,.fixture-settings { visibility: hidden; }', path: '/tmp/bandal-ipad-shell-ai-v2.png' })
    await page.setViewportSize({ width: 1194, height: 834 })
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'suspended')
    await toggle('left')
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadAssistant === 'suspended')
    await page.getByRole('button', { name: '도움 열기 first', exact: true }).tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadAssistant === 'docked')
    assert.equal(await page.locator('.tab-assistant:visible .chat-composer__input').inputValue(), '문서별 대화 초안 보존')
    assert.ok(await composer.evaluate(node => node === document.querySelector('.tab-assistant:not([hidden]) .chat-composer__input')), 'AI composer is never remounted by reflow')
    await page.setViewportSize({ width: 834, height: 1194 })
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadAssistant === 'overlay')
    await page.waitForFunction(() => !!document.activeElement?.closest('.tab-assistant'))
    for (const key of ['Tab', 'Shift+Tab', 'Tab']) { await page.keyboard.press(key); assert.ok(await page.evaluate(() => !!document.activeElement?.closest('.tab-assistant'))) }
    await page.screenshot({ style: '.fixture-materials,.fixture-settings { visibility: hidden; }', path: '/tmp/bandal-ipad-shell-portrait-v2.png' })
    await page.setViewportSize({ width: 1366, height: 900 })
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'docked')
    assert.equal(await shell.getAttribute('data-ipad-assistant'), 'docked')
    assert.deepEqual((await page.evaluate(() => window.ipadLayoutFixture.snapshot())).groups, original.groups)
    await toggle('right')
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadPinned === 'both')
    assert.equal(await page.locator('.tab-assistant:visible').count(), 0)
    await page.setViewportSize({ width: 507, height: 700 })
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadMaterials === 'overlay')
    for (const key of ['Tab', 'Shift+Tab', 'Tab']) { await page.keyboard.press(key); assert.ok(await page.evaluate(() => !!document.activeElement?.closest('.ipad-right-surface'))) }
    await page.keyboard.press('Escape')
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadMaterials === 'closed')
    await page.getByRole('button', { name: '내 공간 닫기', exact: true }).last().tap()
    await page.setViewportSize({ width: 1366, height: 900 })
    assert.equal(await shell.getAttribute('data-ipad-left'), 'closed')
    assert.equal(await shell.getAttribute('data-ipad-materials'), 'closed')
    // Reflow ends modality without moving the user's active search focus.
    await page.setViewportSize({ width: 834, height: 1194 })
    await page.getByRole('button', { name: '내 공간 열기', exact: true }).tap()
    const search = page.locator('#course-search')
    await search.fill('인지')
    await page.setViewportSize({ width: 1366, height: 900 })
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'docked')
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    assert.ok(await search.evaluate(node => document.activeElement === node), 'Overlay-to-dock preserves focused search')
    assert.equal(await search.inputValue(), '인지')
    await search.fill('')
    await page.setViewportSize({ width: 834, height: 1194 })
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'overlay')
    await page.keyboard.press('Escape')
    await page.waitForFunction(() => document.activeElement === document.querySelector('.ipad-shell-chrome button'))
    // Closing an explicitly floating left panel returns focus even beside docked AI.
    await page.setViewportSize({ width: 1366, height: 900 })
    await page.evaluate(() => window.ipadLayoutFixture.select('first'))
    await page.getByRole('button', { name: '도움 열기 first', exact: true }).tap()
    await page.getByRole('button', { name: '내 공간 열기', exact: true }).tap()
    await page.locator('.ipad-left-surface').getByRole('button', { name: '패널 고정 해제', exact: true }).tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'overlay')
    await search.fill('인지')
    await page.keyboard.press('Escape')
    await page.waitForFunction(() => document.activeElement === document.querySelector('.ipad-shell-chrome button')).catch(async error => { console.error('Rail focus diagnostics', await page.evaluate(() => ({active: document.activeElement?.outerHTML.slice(0, 500), shell: document.querySelector('.ipad-shell').dataset, left: window.ipadLayoutFixture.ui.getState().leftRailOpen, focusedInert: !!document.activeElement?.closest('[inert]')}))); throw error })
    assert.equal(await shell.getAttribute('data-ipad-assistant'), 'docked', 'Docked AI stays open without suppressing focus return')
    await page.setViewportSize({ width: 834, height: 1194 })
    await page.getByRole('button', { name: '내 공간 열기', exact: true }).tap()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'overlay')
    await page.locator('.global-navigation').getByRole('button', { name: '학업 보드 열기', exact: true }).tap()
    await page.locator('.board-overlay').waitFor()
    await page.waitForFunction(() => document.querySelector('.ipad-shell').dataset.ipadLeft === 'closed')
    assert.equal(await page.locator('.ipad-panel-backdrop').count(), 0, 'Opening the board releases sidebar modality')
    await page.locator('.board-overlay').getByRole('button', { name: '달력', exact: true }).focus()
    await page.keyboard.press('Tab')
    assert.equal(await page.evaluate(() => !!document.activeElement?.closest('.global-navigation')), false, 'Sidebar focus handling yields to the board')
    assert.deepEqual(errors, [])
    console.log('PASS real shell: desktop icon rail/main sidebar/44px controls, dual docks, suspended promotion, resize restoration, per-document AI draft/mount identity, right ownership and modal keyboard focus')
  } catch (error) {
    console.error('Shell diagnostics', errors, await page.evaluate(() => ({ shell: document.querySelector('.ipad-shell')?.dataset, nav: document.querySelector('.global-navigation')?.outerHTML.slice(0, 700), ui: { left: window.ipadLayoutFixture.ui.getState().leftRailOpen, course: window.ipadLayoutFixture.ui.getState().courseRailOpen, panel: window.ipadLayoutFixture.ui.getState().leftRailPanel, board: window.ipadLayoutFixture.ui.getState().isBoardOverlayOpen } })))
    throw error
  } finally { await page.close() }
}
