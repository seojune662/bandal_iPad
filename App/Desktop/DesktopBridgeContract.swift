    static func capabilities(backendChannels: [String]) -> [String: Any] {
        let available: [String: String] = ["state": "available"]
        let plugin: [String: String] = ["state": "unsupported", "reason": "iPad에서는 로컬 실행 플러그인을 사용할 수 없습니다. 학습 팩과 HTTPS MCP 서버는 별도로 사용할 수 있습니다."]
        let drag: [String: String] = ["state": "unsupported", "reason": "외부 앱으로 보낼 때는 공유 또는 파일에 저장을 사용해 주세요."]
        #if DEBUG
        let unavailable = unsupported
        #else
        let unavailable = unsupported.union(["pdfNative:setEnabled"])
        #endif
        return ["protocolVersion": 1, "platform": "ipad",
                "channels": Array(Set(backendChannels + nativeChannels + extraChannels).subtracting(unavailable)).sorted(),
                "unavailableChannels": unavailable.sorted(),
                "surfaceChannels": ["captureSelection": ["assistant:selection"]],
                "methods": ["invoke": available, "on": available, "pathForFile": available, "openSettings": available, "startMaterialDrag": drag],
