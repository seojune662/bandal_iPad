                // These existing status routes remain the source of truth; callers
                // resolve them for the selected provider/profile when opening a feature.
                "readiness": [
                    "ai": ["channel": "agent:availability", "requestFields": ["provider"], "scope": "configuration"],
                    "account": ["channel": "auth:getState", "requestFields": [], "scope": "configuration"],
                    "appleCalendar": ["channel": "appleCalendar:state", "requestFields": [], "scope": "configuration"],
                    "credentials": ["channel": "credentials:availability", "requestFields": ["profileId"], "scope": "configuration"],
                    "remoteMCP": ["channel": "mcp:list", "requestFields": [], "scope": "configuration"],
                    "mail": ["channel": "mail:state", "requestFields": [], "scope": "configuration"],
                    "legacyPresentation": ["channel": "presentation:runtime", "requestFields": [], "scope": "configuration"],
                    "nativePDF": ["channel": "pdfNative:capabilities", "requestFields": [], "scope": "configuration"]
                ],
                "features": ["materialMove": available, "materialExport": available, "materialShare": available,
                             "externalMaterialDrag": drag, "pluginRuntime": plugin,
                             "pluginDevelopment": plugin, "workflowPacks": available, "remoteMCP": available,
                             "ai": available, "account": available, "appleCalendar": available, "credentials": available,
                             "mail": available, "legacyPresentation": available,
                             "nativePDF": available, "shellDialogs": available, "documentRecovery": available]]
    }

    static func failure(_ error: Error, channel: String, requestID: String = UUID().uuidString) -> [String: Any] {
        let code = (error as? DesktopRuntimeError)?.code ?? (error is CancellationError ? "CANCELLED" : "NATIVE_OPERATION_FAILED")
        let unavailable = unsupported.contains(channel) || ["UNSUPPORTED_CHANNEL", "UNSUPPORTED_ACTION", "ENOSYS"].contains(code)
        return ["__bandalError": ["message": error.localizedDescription, "code": code,
                                  "channel": channel, "requestId": requestID,
                                  "category": unavailable ? "unsupported" : "operation", "retryable": false]]
    }

